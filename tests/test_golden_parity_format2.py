"""Cross-language golden parity for hash format 2 (ITL-898).

Every expected hash in ``tests/golden/format2_v0.5.json`` was generated by
``cargo run --bin emit_golden_format2`` in the Rust starfix crate and is the authoritative
source of truth; the file is a byte-for-byte copy and is never edited here. Every vector
and every relation is checked, with no skips (pyarrow >= 19 decodes every vector).
"""

from __future__ import annotations

import base64
import io
import itertools
import json
from functools import cache
from pathlib import Path
from typing import Any

import pyarrow as pa
import pytest

from starfix import ArrowDigester

_FIXTURE_PATH = Path(__file__).parent / "golden" / "format2_v0.5.json"
_OPTIONS = ("ordered_columns", "ordered_struct_fields")


@cache
def _fixture() -> dict[str, Any]:
    with _FIXTURE_PATH.open(encoding="utf-8") as f:
        return json.load(f)


def _vectors() -> list[dict[str, Any]]:
    return _fixture()["vectors"]


def _relations() -> list[dict[str, Any]]:
    return _fixture()["relations"]


def _hash(vector: dict[str, Any]) -> str:
    vid = vector["id"]
    reader = pa.ipc.open_stream(io.BytesIO(base64.b64decode(vector["ipc_b64"])))
    schema, batches = reader.schema, list(reader)
    options = {name: vector[name] for name in _OPTIONS}
    include_metadata: bool = vector["include_metadata"]
    method = vector["method"]
    if method == "hash_schema":
        result = ArrowDigester.hash_schema(schema, include_metadata=include_metadata, **options)
    elif method == "hash_record_batch":
        assert len(batches) == 1, f"Vector '{vid}': hash_record_batch needs exactly one batch"
        result = ArrowDigester.hash_record_batch(batches[0], include_metadata=include_metadata, **options)
    elif method == "hash_stream":
        digester = ArrowDigester(schema, include_metadata=include_metadata, **options)
        for batch in batches:
            digester.update(batch)
        result = digester.finalize()
    elif method == "hash_array":
        assert len(batches) == 1 and batches[0].num_columns == 1, f"Vector '{vid}': hash_array needs one column"
        result = ArrowDigester.hash_array(batches[0].column(0), **options)
    else:
        pytest.fail(f"Vector '{vid}': unknown method '{method}'")
    return result.hex()


# Counts of the final golden file; the file is append-only, so they can only grow.
_MIN_VECTORS = 423
_MIN_RELATIONS = 114


def test_fixture_is_well_formed() -> None:
    fixture = _fixture()
    assert len(_vectors()) >= _MIN_VECTORS, f"only {len(_vectors())} vectors"
    assert len(_relations()) >= _MIN_RELATIONS, f"only {len(_relations())} relations"
    assert fixture["format"] == 2
    ids = [v["id"] for v in _vectors()]
    assert ids and len(ids) == len(set(ids)), "vector ids must be unique"
    for v in _vectors():
        assert v["expected_hash"].startswith("000002"), v["id"]
        missing = [k for k in (*_OPTIONS, "include_metadata") if k not in v]
        assert not missing, f"{v['id']} lacks {missing}"
    for rel in _relations():
        assert rel["kind"] in ("equal", "different")
        assert len(rel["ids"]) >= 2 and set(rel["ids"]) <= set(ids), rel["ids"]


@pytest.mark.parametrize("vector", _vectors(), ids=lambda v: v["id"])
def test_golden_vector(vector: dict[str, Any]) -> None:
    got = _hash(vector)
    assert got == vector["expected_hash"], (
        f"Vector '{vector['id']}' mismatch: {vector['description']}\n"
        f"  got:      {got}\n  expected: {vector['expected_hash']}"
    )


@pytest.mark.parametrize("relation", _relations(), ids=lambda r: f"{r['kind']}:{'|'.join(r['ids'])}")
def test_golden_relation(relation: dict[str, Any]) -> None:
    """Each relation holds for the pinned values and for the live Python hashes."""
    by_id = {v["id"]: v for v in _vectors()}
    ids = relation["ids"]
    pinned = {i: by_id[i]["expected_hash"] for i in ids}
    live = {i: _hash(by_id[i]) for i in ids}
    for label, hashes in (("pinned", pinned), ("live", live)):
        if relation["kind"] == "equal":
            assert len(set(hashes.values())) == 1, f"relation equal {ids} fails on {label}: {hashes}"
        else:
            for a, b in itertools.combinations(ids, 2):
                assert hashes[a] != hashes[b], f"relation different {ids} fails on {label}: {a} == {b}"
