"""Cross-language golden-hash parity tests for the v0.5 hashing options (ITL-898).

Every expected hash in ``tests/golden/ordered_v0.5.json`` was generated by
``cargo run --bin emit_golden_ordered`` in the Rust starfix crate and is the
authoritative source of truth. The file is a byte-for-byte copy and is never edited
here. Every vector and every relation is checked; nothing is skipped.

Vector methods (IPC stream decoded with ``pyarrow.ipc.open_stream``):

* ``hash_schema``        the stream's schema
* ``hash_record_batch``  exactly one batch
* ``hash_stream``        ``ArrowDigester(schema)``, ``update`` per batch in stream order, ``finalize``
* ``hash_array``         exactly one batch with exactly one column; that column's array
"""

from __future__ import annotations

import base64
import io
import itertools
import json
from functools import cache
from pathlib import Path
from typing import Any

import pyarrow as pa
import pytest

from starfix.arrow_digester import _OPTION_FLAGS, ArrowDigester

_FIXTURE_PATH = Path(__file__).parent / "golden" / "ordered_v0.5.json"


@cache
def _fixture() -> dict[str, Any]:
    with _FIXTURE_PATH.open(encoding="utf-8") as f:
        return json.load(f)


def _vectors() -> list[dict[str, Any]]:
    return _fixture()["vectors"]


def _relations() -> list[dict[str, Any]]:
    return _fixture()["relations"]


def _options(vector: dict[str, Any]) -> dict[str, bool]:
    """The vector's option values, keyed by the Python keyword names."""
    missing = [name for name in _OPTION_FLAGS if name not in vector]
    assert not missing, f"Vector '{vector['id']}' has no value for option(s) {missing}"
    return {name: vector[name] for name in _OPTION_FLAGS}


def _read_ipc(ipc_b64: str) -> tuple[pa.Schema, list[pa.RecordBatch]]:
    reader = pa.ipc.open_stream(io.BytesIO(base64.b64decode(ipc_b64)))
    return reader.schema, list(reader)


def _hash(vector: dict[str, Any]) -> str:
    vid = vector["id"]
    schema, batches = _read_ipc(vector["ipc_b64"])
    options = _options(vector)
    include_metadata: bool = vector["include_metadata"]
    method = vector["method"]

    if method == "hash_schema":
        result = ArrowDigester.hash_schema(schema, include_metadata=include_metadata, **options)
    elif method == "hash_record_batch":
        assert len(batches) == 1, f"Vector '{vid}': hash_record_batch needs exactly one batch"
        result = ArrowDigester.hash_record_batch(batches[0], include_metadata=include_metadata, **options)
    elif method == "hash_stream":
        digester = ArrowDigester(schema, include_metadata=include_metadata, **options)
        for batch in batches:
            digester.update(batch)
        result = digester.finalize()
    elif method == "hash_array":
        assert len(batches) == 1 and batches[0].num_columns == 1, (
            f"Vector '{vid}': hash_array needs exactly one batch with one column"
        )
        result = ArrowDigester.hash_array(batches[0].column(0), **options)
    else:
        pytest.fail(f"Vector '{vid}': unknown method '{method}'")
    return result.hex()


def test_fixture_is_well_formed() -> None:
    vectors = _vectors()
    assert vectors, "golden file has no vectors"
    ids = [v["id"] for v in vectors]
    duplicates = sorted({i for i in ids if ids.count(i) > 1})
    assert not duplicates, f"duplicate vector ids: {duplicates}"
    known = set(ids)
    for rel in _relations():
        assert rel["kind"] in ("equal", "different"), f"unknown relation kind {rel['kind']!r}"
        assert len(rel["ids"]) >= 2, f"relation {rel['ids']} names fewer than two vectors"
        unknown = [i for i in rel["ids"] if i not in known]
        assert not unknown, f"relation {rel['ids']} names unknown vector ids {unknown}"


@pytest.mark.parametrize("vector", _vectors(), ids=lambda v: v["id"])
def test_golden_vector(vector: dict[str, Any]) -> None:
    """Each vector must produce the Rust-authoritative expected_hash."""
    got = _hash(vector)
    assert got == vector["expected_hash"], (
        f"Vector '{vector['id']}' mismatch: {vector['description']}\n"
        f"  got:      {got}\n"
        f"  expected: {vector['expected_hash']}"
    )


@pytest.mark.parametrize(
    "relation", _relations(), ids=lambda r: f"{r['kind']}:{'|'.join(r['ids'])}"
)
def test_golden_relation(relation: dict[str, Any]) -> None:
    """Each relation holds for the pinned values and for the live Python hashes."""
    by_id = {v["id"]: v for v in _vectors()}
    ids = relation["ids"]
    pinned = {i: by_id[i]["expected_hash"] for i in ids}
    live = {i: _hash(by_id[i]) for i in ids}
    for label, hashes in (("pinned", pinned), ("live", live)):
        if relation["kind"] == "equal":
            assert len(set(hashes.values())) == 1, (
                f"relation equal {ids} fails on {label} hashes: {hashes} ({relation.get('why', '')})"
            )
        else:
            for a, b in itertools.combinations(ids, 2):
                assert hashes[a] != hashes[b], (
                    f"relation different {ids} fails on {label} hashes: '{a}' == '{b}' "
                    f"({relation.get('why', '')})"
                )
